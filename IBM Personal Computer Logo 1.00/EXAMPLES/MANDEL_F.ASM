PROC_ENTRY MACRO procname
    DB "&procname", 0
    DW OFFSET AGROUP:procname
ENDM

AGROUP GROUP ADATASEG, CODESEG

ADATASEG SEGMENT PARA PUBLIC 'DATA'
    PROC_ENTRY MANDEL
    PROC_ENTRY READ_CH
    DB 0
ADATASEG ENDS

DISPLAY_WIDTH   EQU 320
DISPLAY_HEIGHT  EQU 200

DRAW_PORT_WIDTH   EQU 240
DRAW_PORT_HEIGHT  EQU 200

DELTA_X  EQU 8000h / DRAW_PORT_WIDTH
DELTA_Y  EQU 8000h / DRAW_PORT_HEIGHT

INITIAL_X    EQU 8000h / (-2)
INITIAL_Y    EQU 8000h / (-2)
MAX_ITER          EQU 16

CGA_VIDEO_PAGE1   EQU 0B800h
CGA_VIDEO_PAGE2   EQU 0BA00h

CODESEG SEGMENT PARA PUBLIC 'CODE'

ASSUME CS:AGROUP, DS:AGROUP, ES:NOTHING

    MANDEL PROC FAR
    PUSHF
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI
    PUSH BP
    PUSH DS
    PUSH ES
    CLD
    MOV AX, CS
    MOV DS, AX
    MOV WORD PTR [CURRENT_X], 0
    MOV WORD PTR [CURRENT_Y], 0
    MOV WORD PTR [DI_EVEN], 0
    MOV WORD PTR [DI_ODD], 0
    MOV AX, CGA_VIDEO_PAGE1
    MOV ES, AX
    MOV DI, [DI_EVEN]
    MOV BX, INITIAL_X
    MOV CX, INITIAL_Y

PIXEL_LOOP:
    XOR SI, SI
    XOR BP, BP
    MOV WORD PTR [ITER], MAX_ITER

ITER_LOOP:
    ADD SI, BX
    ADD BP, CX
    SHL SI, 1
    JO OUTSIDE_CIRCLE
    SHL BP, 1
    JO OUTSIDE_CIRCLE
    MOV AX, SI
    IMUL AX
    SHL AX, 1
    RCL DX, 1
    SHL AX, 1
    RCL DX, 1
    MOV AX, SI
    MOV SI, DX
    IMUL BP
    SHL AX, 1
    RCL DX, 1
    SHL AX, 1
    RCL DX, 1
    MOV AX, BP
    MOV BP, DX
    IMUL AX
    SHL AX, 1
    RCL DX, 1
    SHL AX, 1
    RCL DX, 1
    ADD SI, DX
    JC OUTSIDE_CIRCLE
    SUB SI, DX
    SHR SI, 1
    SHR DX, 1
    SUB SI, DX
    DEC WORD PTR [ITER]
    JNZ ITER_LOOP
    JMP DONE_ITER

OUTSIDE_CIRCLE:
    PUSH CX
    MOV AL, ES:[DI]
    MOV AH, BYTE PTR [CURRENT_X]
    AND AH, 3
    MOV CL, AH
    SHL CL, 1
    MOV AH, 6
    SUB AH, CL
    MOV CL, AH
    MOV SI, [ITER]
    MOV CH, COLORS[SI]
    AND CH, 3
    SHL CH, CL
    OR AL, CH
    POP CX
    STOSB
    DEC DI

DONE_ITER:
    INC WORD PTR [CURRENT_X]
    MOV AL, BYTE PTR [CURRENT_X]
    AND AL, 3
    CMP AL, 0
    JNZ CHECK_LINE_END
    INC DI

CHECK_LINE_END:
    CMP WORD PTR [CURRENT_X], DRAW_PORT_WIDTH
    JE END_OF_LINE
    ADD BX, DELTA_X

NEXT_LINE:
    CMP WORD PTR [CURRENT_Y], DISPLAY_HEIGHT
    JE MANDEL_EXIT
    JMP PIXEL_LOOP

MANDEL_EXIT:
    POP ES
    POP DS
    POP BP
    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX
    POPF
    RET

END_OF_LINE:
    ADD DI, (DISPLAY_WIDTH - DRAW_PORT_WIDTH) / 4
    INC WORD PTR [CURRENT_Y]
    MOV SI, [CURRENT_Y]
    AND SI, 1
    JNZ ODD_LINE
    MOV SI, CGA_VIDEO_PAGE1
    MOV [DI_ODD], DI
    MOV DI, [DI_EVEN]
    JMP VIDEO_PAGE_DONE

ODD_LINE:
    MOV SI, CGA_VIDEO_PAGE2
    MOV [DI_EVEN], DI
    MOV DI, [DI_ODD]

VIDEO_PAGE_DONE:
    MOV ES, SI
    MOV BX, INITIAL_X
    MOV WORD PTR [CURRENT_X], 0
    ADD CX, DELTA_Y
    JMP NEXT_LINE

    MANDEL ENDP

    READ_CH PROC FAR
        PUSHF
        PUSH AX
        XOR AH, AH
        INT 16H
        POP AX
        POPF
        RET
    READ_CH ENDP

    ITER           DW 0
    CURRENT_X      DB 0, 0
    CURRENT_Y      DW 0
    DI_EVEN        DW 0
    DI_ODD         DW 0
    COLORS         DB 1, 2, 3, 1, 2, 3, 1, 2, 3, 1, 2, 3, 1, 2, 3, 1, 2

CODESEG ENDS

END
